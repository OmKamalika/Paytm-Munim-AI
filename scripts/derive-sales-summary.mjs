import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildSalesSummary } from '../lib/sales-summary.js';

/** Read the archived CSV; never execute the source-data generator. */
export function parseSalesCsv(text) {
  const rows = []; let row = []; let field = ''; let quoted = false;
  for (let index = 0; index < text.length; index++) {
    const character = text[index];
    if (quoted) {
      if (character === '"' && text[index + 1] === '"') { field += '"'; index++; }
      else if (character === '"') quoted = false;
      else field += character;
    } else if (character === '"') quoted = true;
    else if (character === ',') { row.push(field); field = ''; }
    else if (character === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (character !== '\r') field += character;
  }
  if (quoted) throw new Error('Unterminated CSV field.');
  if (field.length || row.length) { row.push(field); rows.push(row); }
  const headers = rows.shift()?.map((header) => header.replace(/^\uFEFF/, ''));
  if (!headers?.length || new Set(headers).size !== headers.length || headers.some((header) => !header)) throw new Error('CSV columns must have unique, nonempty headers.');
  return rows.filter((values) => values.some(Boolean)).map((values) => {
    if (values.length !== headers.length) throw new Error('CSV row column count does not match the header.');
    return Object.fromEntries(headers.map((header, index) => [header, values[index]]));
  });
}

async function derive() {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  const bytes = await readFile(join(root, 'data', 'synthetic-v4', 'csv', 'paytm_transactions.csv'));
  const rows = parseSalesCsv(bytes.toString('utf8'));
  const summary = { ...buildSalesSummary(rows), provenance: { source: 'csv/paytm_transactions.csv', sha256: createHash('sha256').update(bytes).digest('hex'), rowCount: rows.length } };
  await writeFile(join(root, 'lib', 'sales-summary.generated.js'), `// Generated by scripts/derive-sales-summary.mjs from archived transaction rows.\nexport const salesSummary = ${JSON.stringify(summary)};\n`, 'utf8');
  process.stdout.write(`Sales summary: ${rows.length} source rows; latest ${summary.latestAvailableAt ?? 'unavailable'}; today ${summary.today.available ? 'available' : 'unavailable'}.\n`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await derive();
