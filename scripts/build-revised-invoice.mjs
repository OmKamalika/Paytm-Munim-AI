// Writes lib/invoice-gd-1182-r1.generated.js: a synthetic, full-body revision of
// Gupta invoice GD-1182 for the outlet-split order. Authored for the demo; it is
// not part of the user-supplied dataset. Run: node scripts/build-revised-invoice.mjs
import { writeFile } from 'node:fs/promises';
import { outletOrder, skuFixture } from '../lib/outlet-order.js';

const inr = (n) => `Rs ${new Intl.NumberFormat('en-IN').format(n)}`;
const upfront = outletOrder.totalAmountInr / 2;
const lines = outletOrder.lines.filter((line) => line.orderUnits > 0).map((line, index) => ({
  lineNo: index + 1, outletId: line.outletId, deliverTo: skuFixture.deliveryAddresses[line.outletId],
  skuId: line.skuId, description: line.sku, units: line.orderUnits, rateInr: line.unitCostInr, amountInr: line.amountInr,
}));
const invoice = {
  synthetic: true,
  provenance: 'Synthetic revision authored for the demo (scripts/build-revised-invoice.mjs). Not part of the user-supplied data; GD-1182 itself still has no body.',
  number: 'GD-1182-R1',
  revisionOf: 'GD-1182',
  supplierId: 'gupta',
  supplierName: 'Gupta Distributors',
  issueDate: '2026-10-30',
  deliveryDate: outletOrder.deliveryDate,
  payTo: { name: 'Gupta Distributors', accountLast4: '7781', rail: 'Paytm for Business (assumed: supplier is a Paytm merchant)' },
  terms: { upfrontPercent: 50, upfrontInr: upfront, upfrontDue: '2026-11-04', creditDays: 45, balanceInr: outletOrder.totalAmountInr - upfront, balanceDue: '2026-12-19', buybackPercent: 50 },
  totalUnits: lines.reduce((sum, line) => sum + line.units, 0),
  amount: outletOrder.totalAmountInr,
  lines,
  hasFullBody: true,
};
invoice.fullBody = [
  `TAX INVOICE ${invoice.number} (revision of ${invoice.revisionOf}) - SYNTHETIC DEMO DOCUMENT`,
  `${invoice.supplierName} -> Sharma General Stores. Issued ${invoice.issueDate}. Delivery ${invoice.deliveryDate}.`,
  ...lines.map((line) => `${line.lineNo}. ${line.skuId} ${line.description} x ${line.units} @ ${inr(line.rateInr)} = ${inr(line.amountInr)} | deliver to ${line.outletId}: ${line.deliverTo}`),
  `Total ${invoice.totalUnits} boxes, ${inr(invoice.amount)}.`,
  `Terms: ${invoice.terms.upfrontPercent}% (${inr(invoice.terms.upfrontInr)}) on delivery ${invoice.terms.upfrontDue}; balance ${inr(invoice.terms.balanceInr)} in ${invoice.terms.creditDays} days (${invoice.terms.balanceDue}); ${invoice.terms.buybackPercent}% buyback on unsold boxes after the season.`,
  `Pay to ${invoice.payTo.name}, account ending ${invoice.payTo.accountLast4}.`,
].join('\n');

const header = '// Generated by scripts/build-revised-invoice.mjs. Synthetic demo document; do not edit by hand.\n';
await writeFile(new URL('../lib/invoice-gd-1182-r1.generated.js', import.meta.url), `${header}export const revisedInvoice = ${JSON.stringify(invoice, null, 2)};\n`);
console.log(`Wrote ${invoice.number}: ${invoice.totalUnits} boxes, ${inr(invoice.amount)}`);
